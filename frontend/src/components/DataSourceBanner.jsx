import { AnimatePresence, motion } from "framer-motion";
import { Archive, Clock, Database, Wifi } from "lucide-react";
import clsx from "clsx";

import { EASE } from "./primitives";
import { fmtRelative } from "../lib/format";

/**
 * States the data can be in, and what we tell the user about each.
 *
 * The honest-labelling requirement is not decoration. The upstream
 * feed is a free tier with a daily quota, so serving yesterday's
 * numbers is a routine condition rather than an outage — and showing
 * them as if they were current would be the one genuinely misleading
 * thing this dashboard could do.
 */
const STATES = {
  live: {
    icon: Wifi,
    tone: "ok",
    label: "Live data",
    detail: "Fetched from Open-Meteo within the last hour.",
  },
  stale_cache: {
    icon: Clock,
    tone: "warn",
    label: "Cached data",
    detail:
      "The upstream feed is temporarily unavailable, so these are the " +
      "last values we retrieved.",
  },
  historical: {
    icon: Archive,
    tone: "warn",
    label: "Historical data",
    detail:
      "The free upstream quota is exhausted, so the map is showing our " +
      "stored dataset rather than current conditions. Forecasts are " +
      "still generated by the model, but from older inputs.",
  },
  none: {
    icon: Database,
    tone: "bad",
    label: "No data",
    detail: "Neither the upstream feed nor the local dataset is available.",
  },
};

const TONES = {
  ok: "border-emerald-400/25 bg-emerald-400/[0.07] text-emerald-200/90",
  warn: "border-amber-400/25 bg-amber-400/[0.07] text-amber-100/90",
  bad: "border-red-400/25 bg-red-400/[0.07] text-red-200/90",
};

const ICON_TONES = {
  ok: "text-emerald-400",
  warn: "text-amber-400",
  bad: "text-red-400",
};

export default function DataSourceBanner({ health }) {
  const cache = health?.upstream_cache;
  const source = cache?.source;

  // Live and fresh is the expected case; saying so on every load would
  // just be noise. Only speak up when the data is not what it seems.
  if (!source || source === "live") return null;

  const state = STATES[source] ?? STATES.none;
  const Icon = state.icon;

  return (
    <AnimatePresence>
      <motion.div
        initial={{ opacity: 0, y: -6, height: 0 }}
        animate={{ opacity: 1, y: 0, height: "auto" }}
        exit={{ opacity: 0, y: -6, height: 0 }}
        transition={{ duration: 0.4, ease: EASE }}
        className={clsx(
          "flex items-start gap-3 rounded-xl border px-4 py-2.5",
          TONES[state.tone],
        )}
      >
        <Icon size={15} className={clsx("mt-0.5 shrink-0", ICON_TONES[state.tone])} />

        <div className="min-w-0 flex-1">
          <div className="flex flex-wrap items-center gap-x-2 gap-y-1">
            <span className="text-xs font-semibold">{state.label}</span>
            {cache?.fetched_at ? (
              <span className="text-[11px] opacity-70">
                &middot; loaded {fmtRelative(cache.fetched_at)}
              </span>
            ) : null}
            {cache?.cities ? (
              <span className="text-[11px] opacity-70">
                &middot; {cache.cities} cities
              </span>
            ) : null}
          </div>

          <p className="mt-0.5 text-[11px] leading-relaxed opacity-80">
            {state.detail}
          </p>

          {cache?.upstream_error ? (
            <p className="mt-1 font-mono text-[10px] leading-relaxed opacity-55">
              {cache.upstream_error}
            </p>
          ) : null}
        </div>
      </motion.div>
    </AnimatePresence>
  );
}
